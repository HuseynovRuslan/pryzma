using System.IdentityModel.Tokens.Jwt;
using System.Security.Claims;
using System.Security.Cryptography;
using System.Text;
using Meydan.Domain.Entities;
using Microsoft.Extensions.Options;
using Microsoft.IdentityModel.Tokens;

namespace Meydan.Infrastructure.Auth;

public sealed record AccessToken(string Token, DateTimeOffset ExpiresAt);

public sealed class AccessTokenService(IOptions<JwtOptions> options, TimeProvider clock)
{
    /// <summary>
    /// Claim carrying a fingerprint of the user's Identity security stamp at issue time. Every request compares it
    /// with the current stamp (see SessionStampCheck), so a password reset — which rotates the stamp — ends access
    /// tokens at once instead of when they expire.
    /// </summary>
    public const string StampClaim = "sst";

    /// <summary>Length of <see cref="StampFingerprint"/>: 32 bytes as unpadded base64url.</summary>
    public const int StampFingerprintLength = 43;

    /// <summary>
    /// The complete SHA-256 digest of the stamp (256 bits, never truncated): 128-bit collision resistance and 256-bit
    /// preimage resistance. The stamp itself — 160 random bits generated by Identity — never leaves the server; the
    /// digest reveals nothing about it and only has to change whenever the stamp does.
    /// </summary>
    public static string StampFingerprint(string? securityStamp) =>
        Base64UrlEncoder.Encode(SHA256.HashData(Encoding.UTF8.GetBytes(securityStamp ?? "")));

    public AccessToken Create(ApplicationUser user, IEnumerable<string> roles)
    {
        var o = options.Value;
        var now = clock.GetUtcNow();
        var expires = now.AddMinutes(o.AccessTokenMinutes);

        var claims = new List<Claim>
        {
            new(JwtRegisteredClaimNames.Sub, user.Id.ToString()),
            new(JwtRegisteredClaimNames.Email, user.Email ?? ""),
            new(JwtRegisteredClaimNames.Jti, Guid.NewGuid().ToString("N")),
            new("given_name", user.FirstName),
            new("family_name", user.LastName),
            new(StampClaim, StampFingerprint(user.SecurityStamp)),
        };
        claims.AddRange(roles.Select(r => new Claim(ClaimTypes.Role, r)));

        var key = new SymmetricSecurityKey(Encoding.UTF8.GetBytes(o.SigningKey));
        var token = new JwtSecurityToken(
            issuer: o.Issuer,
            audience: o.Audience,
            claims: claims,
            notBefore: now.UtcDateTime,
            expires: expires.UtcDateTime,
            signingCredentials: new SigningCredentials(key, SecurityAlgorithms.HmacSha256));

        return new AccessToken(new JwtSecurityTokenHandler().WriteToken(token), expires);
    }

    public static TokenValidationParameters ValidationParameters(JwtOptions o) => new()
    {
        ValidateIssuer = true,
        ValidIssuer = o.Issuer,
        ValidateAudience = true,
        ValidAudience = o.Audience,
        ValidateIssuerSigningKey = true,
        IssuerSigningKey = new SymmetricSecurityKey(Encoding.UTF8.GetBytes(o.SigningKey)),
        ValidateLifetime = true,
        ClockSkew = TimeSpan.FromSeconds(30),
        NameClaimType = JwtRegisteredClaimNames.Sub,
        RoleClaimType = ClaimTypes.Role,
    };
}
